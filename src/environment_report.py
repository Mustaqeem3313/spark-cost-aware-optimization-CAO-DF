"""Generate ``environment.md``: the hardware/software record for the paper's Experimental Setup.

Run once on the study machine. If ``environment.md`` already exists (it may hold
manual corrections such as the disk type), the report is written to
``environment.generated.md`` instead so nothing is overwritten; merge by hand.

Re-run after changing machines, Java/Spark/Python versions, or driver memory,
and record the change with a date.

Usage::

    python src/environment_report.py
"""

from __future__ import annotations

import platform
import subprocess
import sys
from datetime import datetime
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import psutil

from src.baseline_pipeline import PIPELINE_VERSION
from src.paths import ENVIRONMENT_MD_PATH, PROJECT_ROOT
from src.spark_config import BROADCAST_JOIN_THRESHOLD, DRIVER_MEMORY, EXECUTOR_MEMORY, LOCAL_CORES

FALLBACK_PATH = PROJECT_ROOT / "environment.generated.md"


def _pyspark_version() -> str:
    try:
        import pyspark

        return pyspark.__version__
    except ImportError:
        return "NOT INSTALLED -- run pip install -r requirements.txt"


def _java_version() -> str:
    try:
        result = subprocess.run(["java", "-version"], capture_output=True, text=True)
        return result.stderr.strip().splitlines()[0]  # java -version prints to stderr
    except (FileNotFoundError, IndexError):
        return "NOT FOUND -- install JDK 17"


def build_report() -> str:
    cpu_freq = psutil.cpu_freq()
    mem = psutil.virtual_memory()
    return f"""# Experimental Environment
_Auto-generated by `src/environment_report.py` on {datetime.now():%Y-%m-%d %H:%M}._

This file is the source of truth for the paper's Experimental Setup section.
If anything below changes during the study, re-run the script and add a dated note.

## Hardware

| Spec | Value |
|---|---|
| CPU model | {platform.processor() or 'Not detected -- fill in from System Information'} |
| Physical cores | {psutil.cpu_count(logical=False)} |
| Logical cores | {psutil.cpu_count(logical=True)} |
| CPU max frequency (reported) | {f'{cpu_freq.max:.0f} MHz' if cpu_freq else 'Not available'} |
| Total RAM | {mem.total / (1024 ** 3):.1f} GB |
| Disk type | Not auto-detected -- confirm in Device Manager / Task Manager and edit this line |

## Operating System

| Spec | Value |
|---|---|
| OS | {platform.system()} {platform.release()} |
| OS version detail | {platform.version()} |
| Architecture | {platform.machine()} |

## Software Versions

| Spec | Value |
|---|---|
| Python | {sys.version.split()[0]} |
| Java | {_java_version()} |
| PySpark | {_pyspark_version()} |

## Fixed Spark Configuration (all experiments)

| Setting | Value |
|---|---|
| spark.master | local[{LOCAL_CORES}] |
| spark.driver.memory | {DRIVER_MEMORY} |
| spark.executor.memory | {EXECUTOR_MEMORY} (no effect in local mode) |
| spark.sql.adaptive.enabled | false |
| spark.sql.autoBroadcastJoinThreshold | {BROADCAST_JOIN_THRESHOLD} (sort-merge join forced) |
| Baseline pipeline version | {PIPELINE_VERSION} |

## Measurement Isolation Protocol

- [ ] AC power connected, best-performance power mode
- [ ] Background applications closed
- [ ] No other users or heavy processes during the run session
- [ ] Session warm-up plus one discarded warm-up before every measured run
- [ ] Run order randomized within each repetition block
"""


def main() -> None:
    out_path = ENVIRONMENT_MD_PATH
    if out_path.exists():
        out_path = FALLBACK_PATH
        print(f"environment.md already exists; writing the fresh report to {out_path.name} instead.")
    out_path.write_text(build_report(), encoding="utf-8")
    print(f"Wrote {out_path}. Confirm the disk-type line manually.")


if __name__ == "__main__":
    main()
