"""
environment_report.py
======================
Run this ONCE on the machine you will actually run experiments on
(your laptop -- NOT this sandbox, whose specs are irrelevant to your study).

It detects real hardware/software specs and writes environment.md,
which becomes your paper's Experimental Setup section almost verbatim.

Usage:
    python3 src/environment_report.py

Re-run it if you ever change machines, upgrade Java/Spark/Python, or
change spark.driver.memory / spark.executor.memory -- and note the
change with a date in environment.md rather than silently overwriting.
"""

import os
import platform
import psutil
import sys
import subprocess
from datetime import datetime

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
from src.spark_config_v1 import DRIVER_MEMORY, EXECUTOR_MEMORY, BROADCAST_JOIN_THRESHOLD
from src.baseline_pipeline_v1 import PIPELINE_VERSION

try:
    import pyspark
    spark_version = pyspark.__version__
except ImportError:
    spark_version = "NOT INSTALLED -- run pip install -r requirements.txt first"


def get_java_version():
    try:
        result = subprocess.run(["java", "-version"], capture_output=True, text=True)
        # java -version prints to stderr
        return result.stderr.strip().split("\n")[0]
    except FileNotFoundError:
        return "NOT FOUND -- install a JDK (11 or 17) before proceeding"


def get_disk_type_hint():
    # Best-effort hint only -- psutil can't reliably tell SSD vs HDD across
    # all OSes. Confirm manually in your OS's disk utility and edit the
    # generated file if this guess is wrong.
    return "Could not auto-detect -- confirm manually (Disk Utility / Device Manager / lsblk -d -o rota) and edit this line"


def main():
    cpu_freq = psutil.cpu_freq()
    mem = psutil.virtual_memory()

    report = f"""# environment.md
### Auto-generated by `environment_report.py` on {datetime.now().strftime('%Y-%m-%d %H:%M')}

> This file is your paper's Experimental Setup source of truth.
> Re-run the script and update this file (with a dated note, not a silent
> overwrite) if any of the following change during the study.

## Hardware

| Spec | Value |
|---|---|
| CPU model | {platform.processor() or 'Could not auto-detect -- fill in manually from OS System Info'} |
| Physical cores | {psutil.cpu_count(logical=False)} |
| Logical cores (incl. hyperthreading) | {psutil.cpu_count(logical=True)} |
| CPU max frequency | {f'{cpu_freq.max:.0f} MHz' if cpu_freq else 'Not available'} |
| Total RAM | {mem.total / (1024**3):.1f} GB |
| Disk type | {get_disk_type_hint()} |

## Operating System

| Spec | Value |
|---|---|
| OS | {platform.system()} {platform.release()} |
| OS version detail | {platform.version()} |
| Architecture | {platform.machine()} |

## Software Versions (must match requirements.txt exactly)

| Spec | Value |
|---|---|
| Python | {sys.version.split()[0]} |
| Java | {get_java_version()} |
| PySpark | {spark_version} |

## Fixed Spark Configuration (held constant across ALL experiments)

| Setting | Value |
|---|---|
| spark.driver.memory | {DRIVER_MEMORY} |
| spark.executor.memory | {EXECUTOR_MEMORY} (no effect in local mode; executors run inside the driver JVM) |
| spark.master | local[*] |
| spark.sql.adaptive.enabled | false |
| spark.sql.autoBroadcastJoinThreshold | {BROADCAST_JOIN_THRESHOLD} (broadcast joins disabled -> sort-merge join) |
| Baseline pipeline version | {PIPELINE_VERSION} |

## Measurement Isolation Protocol Followed

- [ ] Running on AC power (not battery)
- [ ] Background applications closed
- [ ] No other users/processes active on this machine during the run session
- [ ] Warm-up runs (1-2, discarded) completed before every recorded repetition
- [ ] Run order randomized within each repetition block

---
*If you change machines partway through the study, re-run this script,
rename the old file to environment_<date>.md, and note in your paper's
Limitations section that results before/after this date used different
hardware -- this is exactly the kind of detail a reviewer checks for.*
"""

    out_path = "environment.md"
    if os.path.exists(out_path):
        out_path = "environment.generated.md"
        print("environment.md already exists (it may contain your manual edits, e.g. the disk type),")
        print(f"so the fresh report was written to {out_path} instead. Merge any changes by hand.")
    with open(out_path, "w") as f:
        f.write(report)

    print(f"{out_path} written to current directory.")
    print("IMPORTANT: confirm the disk-type line manually -- it cannot be auto-detected reliably.")


if __name__ == "__main__":
    main()
